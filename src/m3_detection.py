def plot_loss_curves(run_dir: Path, out_path: Path, title: str) -> Path:
    import matplotlib.pyplot as plt

    df = read_results_csv(run_dir)
    fig, axes = plt.subplots(1, 4, figsize=(18, 4))
    for ax, loss in zip(axes[:3], ("box_loss", "cls_loss", "dfl_loss")):
        ax.plot(df["epoch"], df[f"train/{loss}"], label="train")
        ax.plot(df["epoch"], df[f"val/{loss}"], label="validation")
        ax.set_title(loss.replace("_", " "))
        ax.set_xlabel("epoch")
        ax.legend()
    axes[3].plot(df["epoch"], df["metrics/mAP50(B)"], label="mAP@0.5")
    axes[3].plot(df["epoch"], df["metrics/mAP50-95(B)"], label="mAP@0.5:0.95")
    axes[3].set_title("validation mAP")
    axes[3].set_xlabel("epoch")
    axes[3].set_ylim(0, 1.02)
    axes[3].legend()
    fig.suptitle(title)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=120)
    plt.close(fig)
    return out_path


def plot_sweep_curves(run_dirs: dict[str, Path], out_path: Path) -> Path:
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(13, 4))
    for name, run_dir in run_dirs.items():
        df = read_results_csv(run_dir)
        axes[0].plot(df["epoch"], df["val/box_loss"] + df["val/cls_loss"] + df["val/dfl_loss"], label=name)
