def _np(x) -> np.ndarray:
    return x.cpu().numpy() if hasattr(x, "cpu") else np.asarray(x)


def ultralytics_metrics(weights: Path, data_yaml: Path, split: str, imgsz: int = 640,
                        name: str | None = None) -> dict:
    """Standard Ultralytics detection metrics (mAP@0.5, mAP@0.5:0.95, P, R) overall and per class."""
    from ultralytics import YOLO

    model = YOLO(str(weights))
    m = model.val(data=str(data_yaml), split=split, imgsz=imgsz, plots=True, verbose=False,
                  project=str(RUNS_DIR), name=name or f"val_{split}", exist_ok=True)
    box = m.box
    per_class = {}
    for i, cid in enumerate(_np(box.ap_class_index).astype(int)):
        per_class[int(cid)] = {
            "precision": float(_np(box.p)[i]), "recall": float(_np(box.r)[i]),
            "mAP50": float(_np(box.ap50)[i]), "mAP50-95": float(_np(box.ap)[i]),
        }
    return {
        "precision": float(box.mp), "recall": float(box.mr),
        "mAP50": float(box.map50), "mAP50-95": float(box.map),
        "per_class": per_class, "save_dir": str(getattr(m, "save_dir", "")),
    }


def box_iou(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Pairwise IoU between boxes a[N,4] and b[M,4] in xyxy format -> [N,M]."""
    if len(a) == 0 or len(b) == 0:
        return np.zeros((len(a), len(b)))
    x1 = np.maximum(a[:, None, 0], b[None, :, 0])
    y1 = np.maximum(a[:, None, 1], b[None, :, 1])
    x2 = np.minimum(a[:, None, 2], b[None, :, 2])
    y2 = np.minimum(a[:, None, 3], b[None, :, 3])
    inter = np.clip(x2 - x1, 0, None) * np.clip(y2 - y1, 0, None)
    area_a = (a[:, 2] - a[:, 0]) * (a[:, 3] - a[:, 1])
    area_b = (b[:, 2] - b[:, 0]) * (b[:, 3] - b[:, 1])
    return inter / (area_a[:, None] + area_b[None, :] - inter + 1e-9)


@dataclass
class ImageResult:
    image: Path
    gt_cls: np.ndarray
    gt_boxes: np.ndarray
    pr_cls: np.ndarray
    pr_boxes: np.ndarray
    pr_conf: np.ndarray
    pr_status: list  # per prediction: "correct" | "wrong_identity" | "false_positive"
    pr_gt: list      # matched ground-truth index or -1
    pr_iou: list     # IoU with matched ground truth (0 if unmatched)
    gt_status: list  # per ground truth: "correct" | "wrong_identity" | "missed"


def match_predictions(gt_cls, gt_boxes, pr_cls, pr_boxes, pr_conf, iou_thr: float = MATCH_IOU):
    """Greedy, confidence-ordered matching of predictions to ground-truth faces.

    A prediction overlapping an unclaimed face with IoU >= iou_thr claims it:
    "correct" if the identity matches (preferred when several faces overlap),
    otherwise "wrong_identity" (face found, wrong celebrity). Predictions that
    claim nothing are "false_positive"; faces never claimed are "missed".
    """
    ious = box_iou(pr_boxes, gt_boxes)
    gt_status = ["missed"] * len(gt_cls)
    pr_status, pr_gt, pr_iou = ["false_positive"] * len(pr_cls), [-1] * len(pr_cls), [0.0] * len(pr_cls)
    for p in np.argsort(-pr_conf):
        free = [g for g in range(len(gt_cls)) if gt_status[g] == "missed" and ious[p, g] >= iou_thr]
        if not free:
            continue
        same = [g for g in free if gt_cls[g] == pr_cls[p]]
        pool = same or free
        g = max(pool, key=lambda k: ious[p, k])
        status = "correct" if same else "wrong_identity"
        gt_status[g], pr_status[p], pr_gt[p], pr_iou[p] = status, status, g, float(ious[p, g])
    return pr_status, pr_gt, pr_iou, gt_status


def predict_and_match(model, images: list[Path], *, conf: float = DEFAULT_CONF,
                      nms_iou: float = DEFAULT_NMS_IOU, imgsz: int = 640) -> list[ImageResult]:
    """Run the detector on images that have YOLO labels and match predictions to ground truth."""
    results = model.predict(source=[str(p) for p in images], conf=conf, iou=nms_iou, imgsz=imgsz,
                            verbose=False)
    out = []
    for path, r in zip(images, results):
        h, w = r.orig_shape[:2]
        gt_cls, gt_boxes = read_yolo_labels(label_path_for(path), w, h)
        pr_boxes = _np(r.boxes.xyxy).reshape(-1, 4)
        pr_cls = _np(r.boxes.cls).astype(int).reshape(-1)
        pr_conf = _np(r.boxes.conf).reshape(-1)
        pr_status, pr_gt, pr_iou, gt_status = match_predictions(gt_cls, gt_boxes, pr_cls, pr_boxes, pr_conf)
        out.append(ImageResult(path, gt_cls, gt_boxes, pr_cls, pr_boxes, pr_conf,
                               pr_status, pr_gt, pr_iou, gt_status))
    return out


def summarize(results: list[ImageResult]) -> dict:
    """Precision, recall, F1 and IoU at one operating point (conf + NMS threshold)."""
    n_gt = sum(len(r.gt_cls) for r in results)
    n_pred = sum(len(r.pr_cls) for r in results)
    correct = sum(s == "correct" for r in results for s in r.pr_status)
    wrong = sum(s == "wrong_identity" for r in results for s in r.pr_status)
    fp = sum(s == "false_positive" for r in results for s in r.pr_status)
    ious = [iou for r in results for s, iou in zip(r.pr_status, r.pr_iou) if s == "correct"]
    loc_ious = [iou for r in results for s, iou in zip(r.pr_status, r.pr_iou) if s != "false_positive"]
    precision = correct / n_pred if n_pred else 0.0
    recall = correct / n_gt if n_gt else 0.0
    return {
        "faces": n_gt, "predictions": n_pred, "correct": correct, "wrong_identity": wrong,
        "false_positive": fp, "missed": n_gt - correct - wrong,
        "precision": precision, "recall": recall,
        "f1": 2 * precision * recall / (precision + recall) if precision + recall else 0.0,
        "face_localization_rate": (correct + wrong) / n_gt if n_gt else 0.0,
        "mean_iou": float(np.mean(ious)) if ious else 0.0,
        "mean_iou_all_localized": float(np.mean(loc_ious)) if loc_ious else 0.0,
    }


def per_class_iou(results: list[ImageResult], names: dict[int, str]) -> dict[int, dict]:
    stats = {cid: {"faces": 0, "correct": 0, "ious": []} for cid in names}
    for r in results:
        for g, cid in enumerate(r.gt_cls):
            stats[int(cid)]["faces"] += 1
        for s, g, iou in zip(r.pr_status, r.pr_gt, r.pr_iou):
            if s == "correct":
                cid = int(r.gt_cls[g])
                stats[cid]["correct"] += 1
                stats[cid]["ious"].append(iou)
    return {cid: {"faces": v["faces"], "correct": v["correct"],
                  "mean_iou": float(np.mean(v["ious"])) if v["ious"] else float("nan")}
            for cid, v in stats.items()}


def threshold_sweep(weights: Path, images: list[Path], *, confs=(0.05, 0.1, 0.25, 0.4, 0.5, 0.6, 0.75, 0.9),
                    nms_ious=(0.3, 0.45, 0.6, 0.7, 0.8), imgsz: int = 640) -> tuple["pd.DataFrame", "pd.DataFrame"]:
    """Inference-time sweep: confidence threshold (NMS fixed at default) and NMS IoU (conf fixed at default)."""
    import pandas as pd
    from ultralytics import YOLO

    model = YOLO(str(weights))
    conf_rows = [{"conf": c, "nms_iou": DEFAULT_NMS_IOU,
                  **summarize(predict_and_match(model, images, conf=c, nms_iou=DEFAULT_NMS_IOU, imgsz=imgsz))}
                 for c in confs]
    nms_rows = [{"conf": DEFAULT_CONF, "nms_iou": t,
                 **summarize(predict_and_match(model, images, conf=DEFAULT_CONF, nms_iou=t, imgsz=imgsz))}
                for t in nms_ious]
    return pd.DataFrame(conf_rows), pd.DataFrame(nms_rows)


