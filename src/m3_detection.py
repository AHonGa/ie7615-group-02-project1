COLORS = {"correct": (40, 170, 40), "wrong_identity": (0, 0, 220), "false_positive": (0, 140, 255),
          "missed": (200, 60, 200)}  # BGR


def draw_result(r: ImageResult, names: dict[int, str]) -> np.ndarray:
    """Predictions coloured by outcome; missed faces drawn as dashed magenta boxes."""
    import cv2

    img = cv2.imread(str(r.image))
    thick = max(2, img.shape[0] // 320)
    for g, status in enumerate(r.gt_status):
        if status == "missed":
            x1, y1, x2, y2 = r.gt_boxes[g].astype(int)
            for x in range(x1, x2, 12):
                cv2.line(img, (x, y1), (min(x + 6, x2), y1), COLORS["missed"], thick)
                cv2.line(img, (x, y2), (min(x + 6, x2), y2), COLORS["missed"], thick)
            for y in range(y1, y2, 12):
                cv2.line(img, (x1, y), (x1, min(y + 6, y2)), COLORS["missed"], thick)
                cv2.line(img, (x2, y), (x2, min(y + 6, y2)), COLORS["missed"], thick)
            cv2.putText(img, f"MISSED {names[int(r.gt_cls[g])]}", (x1 + 3, y2 - 6),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.4, COLORS["missed"], 1, cv2.LINE_AA)
    for p in range(len(r.pr_cls)):
        x1, y1, x2, y2 = r.pr_boxes[p].astype(int)
        color = COLORS[r.pr_status[p]]
        cv2.rectangle(img, (x1, y1), (x2, y2), color, thick)
        label = f"{names[int(r.pr_cls[p])]} {r.pr_conf[p]:.2f}"
        if r.pr_status[p] == "wrong_identity":
            label += f" (is {names[int(r.gt_cls[r.pr_gt[p]])]})"
        (tw, th), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.42, 1)
        ty = max(y1, th + 4)
        # Keep the label inside the image: shift it left when it would run past the right edge.
        lx = max(0, min(x1, img.shape[1] - tw - 4))
        cv2.rectangle(img, (lx, ty - th - 4), (lx + tw + 4, ty), color, -1)
        cv2.putText(img, label, (lx + 2, ty - 3), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (255, 255, 255), 1,
                    cv2.LINE_AA)
    return img


def caption_for(r: ImageResult, names: dict[int, str], context: str) -> str:
    n = len(r.gt_cls)
    correct = r.gt_status.count("correct")
    parts = [f"{context}: {correct}/{n} faces detected with the correct identity"]
    good_conf = [c for c, s in zip(r.pr_conf, r.pr_status) if s == "correct"]
    if good_conf:
        parts.append(f"confidence {min(good_conf):.2f}-{max(good_conf):.2f}")
    missed = [names[int(r.gt_cls[g])] for g, s in enumerate(r.gt_status) if s == "missed"]
    if missed:
        parts.append("missed " + ", ".join(missed))
    confusions = [f"{names[int(r.gt_cls[g])]} predicted as {names[int(r.pr_cls[p])]}"
                  for p, (s, g) in enumerate(zip(r.pr_status, r.pr_gt)) if s == "wrong_identity"]
    if confusions:
        parts.append("identity confusion: " + "; ".join(confusions))
    fps = sum(s == "false_positive" for s in r.pr_status)
    if fps:
        parts.append(f"{fps} extra box(es) on background or duplicate faces")
    return f"**{outcome_label(correct, n)}.** " + "; ".join(parts) + "."


def outcome_label(correct: int, faces: int) -> str:
    """Success: at least 8 of 9 faces right; Partial: at least half; Failure: fewer."""
    share = correct / faces if faces else 0.0
    return "Success" if share >= 8 / 9 else "Partial" if share >= 0.5 else "Failure"


def make_stress_images(images: list[Path], out_dir: Path) -> list[tuple[Path, str]]:
    """Harder, labelled variants of test images to surface instructive failures.

    small  : frame shrunk to 45% and placed on a grey canvas (smaller faces)
    dark   : exposure cut to 30% (poor lighting)
    blur   : heavy Gaussian blur (out-of-focus photo)
    crowded: two frames side by side squeezed into one 640 frame (18 small faces)
    Labels are transformed exactly, so the same matching code scores them.
    """
    import cv2

    (out_dir / "images").mkdir(parents=True, exist_ok=True)
    (out_dir / "labels").mkdir(parents=True, exist_ok=True)
    made = []

    def save(img, rows, stem, desc):
        path = out_dir / "images" / f"{stem}.jpg"
        cv2.imwrite(str(path), img)
        (out_dir / "labels" / f"{stem}.txt").write_text(
            "\n".join(f"{int(c)} {x:.6f} {y:.6f} {w:.6f} {h:.6f}" for c, x, y, w, h in rows) + "\n")
        made.append((path, desc))

    def rows_of(p):
        return np.loadtxt(label_path_for(p), ndmin=2)

    for p in images[:2]:
        img = cv2.imread(str(p))
        h, w = img.shape[:2]
        rows = rows_of(p)
        s, ox, oy = 0.45, 0.30, 0.40
        canvas = np.full_like(img, 128)
        small = cv2.resize(img, (int(w * s), int(h * s)))
        x0, y0 = int(w * ox), int(h * oy)
        canvas[y0:y0 + small.shape[0], x0:x0 + small.shape[1]] = small
        r2 = rows.copy()
        r2[:, 1] = rows[:, 1] * small.shape[1] / w + x0 / w
        r2[:, 2] = rows[:, 2] * small.shape[0] / h + y0 / h
        r2[:, 3] = rows[:, 3] * small.shape[1] / w
        r2[:, 4] = rows[:, 4] * small.shape[0] / h
        save(canvas, r2, f"{p.stem}_small", "Stress test (faces shrunk to 45%)")
        save(np.clip(img.astype(np.float32) * 0.30, 0, 255).astype(np.uint8), rows, f"{p.stem}_dark",
             "Stress test (exposure cut to 30%)")
        save(cv2.GaussianBlur(img, (0, 0), 4), rows, f"{p.stem}_blur", "Stress test (heavy blur)")
    if len(images) >= 2:
        a, b = cv2.imread(str(images[0])), cv2.imread(str(images[1]))
        h, w = a.shape[:2]
        both = cv2.resize(np.hstack([a, cv2.resize(b, (w, h))]), (w, h))
        ra, rb = rows_of(images[0]).copy(), rows_of(images[1]).copy()
        for rr, off in ((ra, 0.0), (rb, 0.5)):
            rr[:, 1] = rr[:, 1] / 2 + off
            rr[:, 3] = rr[:, 3] / 2
        save(both, np.vstack([ra, rb]), "crowded_two_frames", "Stress test (two frames squeezed together)")
    return made


def build_gallery(weights: Path, names: dict[int, str], out_dir: Path, dataset_dir: Path | None = None,
                  conf: float = DEFAULT_CONF, nms_iou: float = DEFAULT_NMS_IOU, imgsz: int = 640) -> "pd.DataFrame":
    """Annotated predictions for every test image plus stress variants, with captions."""
    import cv2
    import pandas as pd
    from ultralytics import YOLO

    dataset_dir = Path(dataset_dir or DATASET_DIR)
    model = YOLO(str(weights))
    out_dir.mkdir(parents=True, exist_ok=True)
    groups = [(list_images("test", dataset_dir), "Test split")]
    stress = make_stress_images(list_images("test", dataset_dir), out_dir.parent / "stress_test")
    rows = []
    for imgs, context in groups + [([p for p, _ in stress], None)]:
        contexts = [context] * len(imgs) if context else [d for _, d in stress]
        for r, ctx in zip(predict_and_match(model, imgs, conf=conf, nms_iou=nms_iou, imgsz=imgsz), contexts):
            out_name = f"{len(rows) + 1:02d}_{r.image.stem}.jpg"
            cv2.imwrite(str(out_dir / out_name), draw_result(r, names))
            s = summarize([r])
            rows.append({"file": out_name, "source": ctx, "faces": s["faces"], "correct": s["correct"],
                         "missed": s["missed"], "wrong_identity": s["wrong_identity"],
                         "false_positive": s["false_positive"], "caption": caption_for(r, names, ctx)})
    df = pd.DataFrame(rows)
    lines = ["# Milestone 3 detection gallery", "",
             f"Fine-tuned YOLOv8n, confidence >= {conf}, NMS IoU {nms_iou}. Grades: **Success** = at least 8 of 9 faces "
             "correctly identified, **Partial** = at least half, **Failure** = fewer. Box colours: "
             "**green** = correct identity, **red** = face found but wrong identity (true identity in brackets), "
             "**orange** = false positive, **dashed magenta** = missed face.", "",
             "Stress-test images are harder, exactly-relabelled variants of test frames "
             "(smaller faces, low light, blur, crowding); they are included to show failure modes "
             "and are not part of the reported test metrics.", ""]
    for row in rows:
        lines += [f"### {row['file']}", "", f"![{row['file']}]({row['file']})", "", row["caption"], ""]
    (out_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")
    df.to_csv(out_dir / "gallery_index.csv", index=False)
    return df


