def load_class_names(dataset_dir: Path | None = None) -> dict[int, str]:
    """class_id -> 'celeb_<CelebA identity>' from the dataset's classes.json (same ids in M2 and M3)."""
    dataset_dir = Path(dataset_dir or DATASET_DIR)
    mapping = json.loads((dataset_dir / "classes.json").read_text(encoding="utf-8"))
    return {int(cid): f"celeb_{celeb}" for celeb, cid in sorted(mapping.items(), key=lambda kv: kv[1])}


def is_our_group(name: str) -> bool:
    return name.replace("celeb_", "") in OUR_GROUP_CELEB_IDS


def write_data_yaml(dataset_dir: Path | None = None) -> Path:
    """Write detection_dataset/data.yaml and return its absolute path.

    No `path:` key on purpose: Ultralytics then resolves train/val/test relative
    to the YAML's own folder, so the same file works on Colab, Windows and Linux
    as long as the *absolute* YAML path is passed in.
    """
    dataset_dir = Path(dataset_dir or DATASET_DIR)
    names = load_class_names(dataset_dir)
    lines = [
        "# YOLOv8 dataset config for the synthetic multi-celebrity detection dataset.",
        "# Split folders are resolved relative to this file. Generated by src/m3_detection.py.",
        "train: train/images",
        "val: val/images",
        "test: test/images",
        f"nc: {len(names)}",
        "names:",
    ]
    lines += [f"  {cid}: {name}" for cid, name in names.items()]
    path = dataset_dir / "data.yaml"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path.resolve()


def list_images(split: str, dataset_dir: Path | None = None) -> list[Path]:
    folder = Path(dataset_dir or DATASET_DIR) / split / "images"
    return sorted(p for p in folder.iterdir() if p.suffix.lower() in IMG_EXTS)


def label_path_for(image_path: Path) -> Path:
    return image_path.parent.parent / "labels" / f"{image_path.stem}.txt"


def read_yolo_labels(label_path: Path, width: int, height: int) -> tuple[np.ndarray, np.ndarray]:
    """Return (class_ids[N], boxes_xyxy_pixels[N,4]) from a YOLO label file."""
    if not label_path.is_file() or not label_path.read_text().strip():
        return np.zeros(0, dtype=int), np.zeros((0, 4))
    rows = np.loadtxt(label_path, ndmin=2)
    cls = rows[:, 0].astype(int)
    xc, yc, w, h = rows[:, 1] * width, rows[:, 2] * height, rows[:, 3] * width, rows[:, 4] * height
    boxes = np.stack([xc - w / 2, yc - h / 2, xc + w / 2, yc + h / 2], axis=1)
    return cls, boxes


def split_summary(dataset_dir: Path | None = None) -> "pd.DataFrame":
    """Images, faces and identity coverage per split."""
    import pandas as pd

    dataset_dir = Path(dataset_dir or DATASET_DIR)
    names = load_class_names(dataset_dir)
    rows = []
    for split in ("train", "val", "test"):
        images = list_images(split, dataset_dir)
        classes = []
        for img in images:
            text = label_path_for(img).read_text().split()
            classes += [int(float(v)) for v in text[0::5]]
        present = sorted(set(classes))
        missing = [names[c] for c in names if c not in present]
        rows.append({
            "split": split,
            "images": len(images),
            "faces": len(classes),
            "identities_present": len(present),
            "identities_missing": ", ".join(missing) if missing else "-",
        })
    return pd.DataFrame(rows)


