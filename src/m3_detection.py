def fmt(x, digits: int = 3) -> str:
    """Numbers for tables: NaN -> n/a, whole numbers without decimals, tiny values (e.g. lr0) unrounded."""
    try:
        if x != x:  # NaN
            return "n/a"
        if float(x).is_integer():
            return str(int(x))
        if 0 < abs(x) < 0.01:
            return f"{x:g}"
        return f"{x:.{digits}f}"
    except (TypeError, ValueError):
        return str(x)


def md_table(df, digits: int = 3) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join(fmt(row[c], digits) if isinstance(row[c], float) else str(row[c])
                                       for c in cols) + " |")
    return "\n".join(lines)
