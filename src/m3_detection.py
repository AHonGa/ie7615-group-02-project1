@dataclass
class RunConfig:
    """One training configuration in the sweep."""

    name: str
    description: str
    model: str = "yolov8n.pt"  # COCO-pretrained starting checkpoint
    lr0: float = 0.001
    imgsz: int = 640
    aug: dict = field(default_factory=dict)  # Ultralytics augmentation overrides

    def as_row(self) -> dict:
        aug = ", ".join(f"{k}={v}" for k, v in self.aug.items()) or "Ultralytics defaults"
        return {"run": self.name, "model": self.model.replace(".pt", ""), "lr0": self.lr0, "imgsz": self.imgsz, "augmentation": aug,
                "what changes": self.description}


# Light augmentation: no mosaic/mixing, gentle colour and scale jitter. The
# dataset was already augmented offline in Milestone 2, so this tests whether
# YOLO's own (strong) online augmentation still helps on top of that.
LIGHT_AUG = {"mosaic": 0.0, "scale": 0.2, "translate": 0.05, "hsv_h": 0.005, "hsv_s": 0.3, "hsv_v": 0.2}

