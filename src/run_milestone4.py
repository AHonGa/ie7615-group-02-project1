"""Milestone 4 end to end: 13-identity classifier, integrated pipeline evaluation, final gallery.

From the repo root (works on CPU; a GPU just makes step 1 faster):
    python src/run_milestone4.py            # full run (~5-10 min on a laptop CPU)
    python src/run_milestone4.py --smoke    # 1-epoch check that everything runs (~1 min)
    python src/run_milestone4.py --skip-training   # reuse models/celeba_resnet18_13id.pt

Steps
 1. Train the Milestone 1 ResNet18 on all 13 identities (photo split shared with Milestone 3).
 2. Evaluate it on single-face validation/test photos (accuracy, per identity, confusion matrix).
 3. Evaluate the integrated pipeline on the multi-face grids: detector alone vs detector boxes +
    classifier names vs fusion. The setting is chosen on validation; test is reported once.
 4. Build the final gallery: >=20 correct and >=5 misclassified single faces, >=10 multi-face images.
 5. Save results/milestone4/summary.json and results_tables.md for the final report.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import m3_detection as m3  # noqa: E402
import m4_pipeline as m4  # noqa: E402

GALLERY = m4.RESULTS_DIR / "gallery"


def step_train(epochs: int, smoke: bool, skip: bool):
    m4.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    import pandas as pd

    hist_csv = m4.RESULTS_DIR / "classifier_history.csv"
    if skip and m4.CLASSIFIER_WEIGHTS.is_file():
        print(f"Reusing {m4.CLASSIFIER_WEIGHTS}")
        hist = pd.read_csv(hist_csv) if hist_csv.is_file() else None
    else:
        hist = m4.train_classifier(epochs=1 if smoke else epochs, limit=8 if smoke else None)
    if hist is not None:
        m4.plot_classifier_history(hist, m4.RESULTS_DIR / "classifier_curves.png")
    return hist


def step_classifier_eval(clf):
    m4.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    ev = {s: m4.evaluate_classifier(clf, s) for s in ("val", "test")}
    for s, df in ev.items():
        df.drop(columns=["path"]).to_csv(m4.RESULTS_DIR / f"classifier_{s}_predictions.csv", index=False)
    m4.per_identity_accuracy(ev["test"]).to_csv(m4.RESULTS_DIR / "classifier_test_per_identity.csv", index=False)
    m4.plot_confusion(ev["test"], m4.RESULTS_DIR / "classifier_confusion_test.png",
                      f"Classifier confusion matrix, test photos ({len(ev['test'])})")
    for s, df in ev.items():
        print(f"classifier {s}: {int(df.correct.sum())}/{len(df)} = {df.correct.mean():.3f}")
    return ev


def step_pipeline(pipe):
    m4.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    val = m4.compare_modes(pipe, "val")
    test = m4.compare_modes(pipe, "test")
    # choose on validation only: highest accuracy, then fewest extra boxes
    cands = val[val["agnostic_nms"]].sort_values(["accuracy", "extra_boxes"], ascending=[False, True])
    chosen = cands.iloc[0]["mode"]
    val.to_csv(m4.RESULTS_DIR / "pipeline_modes_val.csv", index=False)
    test.to_csv(m4.RESULTS_DIR / "pipeline_modes_test.csv", index=False)
    print(val.round(3).to_string(index=False))
    print(test.round(3).to_string(index=False))
    print("chosen on validation:", chosen)
    return val, test, chosen


def _pick_correct(df, n=20):
    """At least one correct photo per identity, then fill with the rest (deterministic)."""
    ok = df[df["correct"]].sort_values(["label", "conf"], ascending=[True, False])
    first = ok.groupby("label").head(1)
    rest = ok.drop(first.index)
    return (list(first.index) + list(rest.index))[:n]


def step_gallery(clf, pipe, ev, mode):
    import cv2
    import pandas as pd

    if GALLERY.exists():
        shutil.rmtree(GALLERY)
    for sub in ("single_correct", "single_misclassified", "multi_face"):
        (GALLERY / sub).mkdir(parents=True)
    lines = ["# Milestone 4 final results gallery", "",
             "Generated by `src/run_milestone4.py` from held-out photos and grids (never used for training).", ""]

    # ---- single faces: correct ----
    test = ev["test"]
    picks = _pick_correct(test, 20)
    lines += ["## 1. Correctly classified single faces", "",
              f"{len(picks)} test photos named correctly by the 13-identity ResNet18 classifier "
              f"(test accuracy {int(test.correct.sum())}/{len(test)}). At least one per identity.", "",
              "| # | image | true identity | predicted | confidence |", "|---|---|---|---|---|"]
    for k, i in enumerate(picks, 1):
        r = test.loc[i]
        name = f"{k:02d}_{r['true']}.jpg"
        cv2.imwrite(str(GALLERY / "single_correct" / name), m4.single_face_card(r, True))
        lines.append(f"| {k} | ![](single_correct/{name}) | {r['true']} | {r['pred']} | {r['conf']:.2f} |")

    # ---- single faces: misclassified (test first, then validation, then stress copies) ----
    wrong = test[~test["correct"]].assign(source="test photo")
    if len(wrong) < 5:
        v = ev["val"]
        wrong = pd.concat([wrong, v[~v["correct"]].assign(source="validation photo")])
    if len(wrong) < 5:
        stress = m4.make_stress_photos(test, m4.RESULTS_DIR / "stress_single")
        sev = m4.evaluate_photo_rows(clf, stress)
        sev = sev[~sev["correct"]].assign(source=lambda d: "stress copy (" + d["variant"] + ") of a test photo")
        wrong = pd.concat([wrong, sev.sort_values("conf", ascending=False)])
    wrong = wrong.head(max(5, (~test["correct"]).sum())).reset_index(drop=True)
    lines += ["", "## 2. Misclassified single faces", "",
              "Each card shows the photo, the wrong prediction, and a training photo of the predicted identity.", ""]
    for k, r in wrong.iterrows():
        name = f"{k + 1:02d}_{r['true']}_as_{r['pred']}.jpg"
        cv2.imwrite(str(GALLERY / "single_misclassified" / name), m4.single_face_card(r, False))
        lines += [f"### {k + 1}. {r['true']} predicted as {r['pred']} ({r['source']})", "",
                  f"![](single_misclassified/{name})", "", m4.misclassification_note(r), ""]

    # ---- multi-face ----
    names = m4.class_names()
    multi = [(p, "Test grid") for p in m3.list_images("test")]
    stress_dir = m3.RESULTS_DIR / "stress_test" / "images"
    if stress_dir.is_dir():
        multi += [(p, "Stress test (from Milestone 3)") for p in sorted(stress_dir.glob("*.jpg"))]
    lines += ["## 3. Multi-face detection and identification", "",
              f"Integrated pipeline (`{mode}` mode). Green = correct identity, red = wrong identity "
              "(true identity in brackets), orange = extra box, dashed magenta = missed face.", ""]
    rows = []
    for k, (p, ctx) in enumerate(multi, 1):
        r = pipe.evaluate([p], mode)[0]
        name = f"{k:02d}_{p.stem}.jpg"
        cv2.imwrite(str(GALLERY / "multi_face" / name), m3.draw_result(r, names))
        cap = m3.caption_for(r, names, ctx)
        s = m3.summarize([r])
        rows.append({"file": name, "source": ctx, "faces": s["faces"], "correct": s["correct"]})
        lines += [f"### {name}", "", f"![](multi_face/{name})", "", cap, ""]
    (GALLERY / "README.md").write_text("\n".join(lines), encoding="utf-8")
    pd.DataFrame(rows).to_csv(GALLERY / "multi_face_index.csv", index=False)
    return {"single_correct": len(picks), "single_misclassified": len(wrong), "multi_face": len(multi),
            "misclassified_sources": wrong["source"].value_counts().to_dict()}


def step_summary(hist, ev, val, test, chosen, gallery_counts, clf):
    m4.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    t = test.set_index(test["mode"] + "_" + test["agnostic_nms"].astype(str))
    best = test[(test["mode"] == chosen) & (test["agnostic_nms"])].iloc[0]
    det = test[(test["mode"] == "detector") & (~test["agnostic_nms"])].iloc[0]
    summary = {
        "classifier": {"best_epoch": getattr(clf, "best_epoch", None),
                       "val_accuracy": float(ev["val"].correct.mean()),
                       "test_accuracy": float(ev["test"].correct.mean()),
                       "test_correct": int(ev["test"].correct.sum()), "test_photos": len(ev["test"])},
        "pipeline": {"chosen_mode": chosen, "test_correct": int(best["correct"]), "test_faces": int(best["faces"]),
                     "test_accuracy": float(best["accuracy"]), "test_extra_boxes": int(best["extra_boxes"]),
                     "test_mean_iou": float(best["mean_iou"]),
                     "milestone3_detector_test_correct": int(det["correct"])},
        "gallery": gallery_counts,
    }
    (m4.RESULTS_DIR / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    md = ["# Milestone 4 result tables (generated)", "",
          "## Data split (face photos, shared by classifier and detector)", "", m3.md_table(m4.split_counts()), "",
          "## Classifier (single face photos)", "",
          f"Validation accuracy {summary['classifier']['val_accuracy']:.3f}, test accuracy "
          f"{summary['classifier']['test_accuracy']:.3f} ({summary['classifier']['test_correct']}/"
          f"{summary['classifier']['test_photos']}); best epoch {summary['classifier']['best_epoch']}.", "",
          m3.md_table(m4.per_identity_accuracy(ev["test"])), "",
          "## Integrated pipeline (multi-face grids)", "", "Validation (used to choose the setting):", "",
          m3.md_table(val.drop(columns=["mode", "agnostic_nms"])), "", "Test:", "",
          m3.md_table(test.drop(columns=["mode", "agnostic_nms"])), "",
          f"Chosen on validation: `{chosen}`.", ""]
    (m4.RESULTS_DIR / "results_tables.md").write_text("\n".join(md), encoding="utf-8")
    return summary


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--epochs", type=int, default=30)
    ap.add_argument("--smoke", action="store_true", help="1 epoch on a few photos, to check everything runs")
    ap.add_argument("--skip-training", action="store_true")
    args = ap.parse_args()

    m4.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    print(m4.split_counts().to_string(index=False))
    hist = step_train(args.epochs, args.smoke, args.skip_training)
    clf = m4.Classifier()
    ev = step_classifier_eval(clf)
    pipe = m4.Pipeline(classifier=clf)
    val, test, chosen = step_pipeline(pipe)
    counts = step_gallery(clf, pipe, ev, chosen)
    summary = step_summary(hist, ev, val, test, chosen, counts, clf)
    print(json.dumps(summary, indent=2))
    print(f"\nDone. Results: {m4.RESULTS_DIR}\nGallery: {GALLERY / 'README.md'}")
    if args.smoke:
        print("\nSMOKE TEST ONLY (1 epoch, few photos). Now run without --smoke for the real results.")


if __name__ == "__main__":
    main()
